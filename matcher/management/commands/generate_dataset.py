"""
Builds the synthetic resume/JD fit dataset used to train both models.

DATA DISCLOSURE: No suitable public, freely-licensed dataset of labeled
resume<->job-description fit pairs could be found (public options were
either plain resume corpora with job-category labels and no JD pairing, or
messy personal repos with unclear licensing). This dataset is therefore
synthetically generated by this script — AI-generated synthetic text, not
real resumes or real job postings — built from template sentences and a
curated skill bank (see matcher/ml/skills.py). Labels are assigned from a
skill-overlap + experience rule with a small amount of injected noise, so
the classification task is realistic (not perfectly separable) without
being real-world data.
"""

import csv
import random
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand

from matcher.ml.skills import GENERAL_SKILLS, ROLE_SKILLS

ROLES = list(ROLE_SKILLS.keys())

JD_INTROS = [
    "We are hiring a {role} to join our growing team.",
    "Our company is looking for an experienced {role} to help us scale.",
    "{role} wanted for a fast-paced, collaborative environment.",
    "Join us as a {role} and make an impact from day one.",
]
JD_REQUIREMENTS = [
    "The ideal candidate has {years}+ years of experience and is skilled in {skills}.",
    "Requirements: at least {years} years of relevant experience, with hands-on skills in {skills}.",
    "You should have {years}+ years in the field and be comfortable with {skills}.",
]
JD_CLOSINGS = [
    "Strong communication and teamwork are a plus.",
    "We value problem solving and a growth mindset.",
    "Competitive salary and benefits offered.",
    "Remote-friendly with flexible hours.",
]

RESUME_INTROS = [
    "Experienced {role} with a passion for building great products.",
    "{role} with a proven track record of delivering results.",
    "Motivated {role} eager to contribute technical expertise.",
    "Detail-oriented {role} with hands-on experience across projects.",
]
RESUME_EXPERIENCE = [
    "Has {years} years of professional experience.",
    "Brings {years} years of hands-on industry experience.",
    "{years} years working in related roles.",
]
RESUME_SKILLS_LINE = [
    "Proficient in {skills}.",
    "Core skills include {skills}.",
    "Hands-on experience with {skills}.",
]
RESUME_CLOSINGS = [
    "Known for strong communication and teamwork.",
    "Comfortable working independently or in a team.",
    "Continuously learning new tools and technologies.",
]


def build_jd(role, rng):
    pool = ROLE_SKILLS[role]
    required_skills = rng.sample(pool, k=rng.randint(5, min(8, len(pool))))
    years_required = rng.randint(1, 7)
    text = " ".join([
        rng.choice(JD_INTROS).format(role=role),
        rng.choice(JD_REQUIREMENTS).format(years=years_required, skills=", ".join(required_skills)),
        rng.choice(JD_CLOSINGS),
    ])
    return text, set(required_skills), years_required


def build_resume(role, rng):
    pool = ROLE_SKILLS[role]
    own_skills = set(rng.sample(pool, k=rng.randint(4, min(10, len(pool)))))

    # A little cross-role realism: people often have skills outside their
    # main role's "core" list.
    if rng.random() < 0.4:
        other_role = rng.choice([r for r in ROLES if r != role])
        other_pool = ROLE_SKILLS[other_role]
        own_skills |= set(rng.sample(other_pool, k=min(2, len(other_pool))))

    if rng.random() < 0.5:
        own_skills |= set(rng.sample(GENERAL_SKILLS, k=rng.randint(1, 2)))

    years = rng.randint(0, 10)

    text = " ".join([
        rng.choice(RESUME_INTROS).format(role=role),
        rng.choice(RESUME_EXPERIENCE).format(years=years),
        rng.choice(RESUME_SKILLS_LINE).format(skills=", ".join(sorted(own_skills))),
        rng.choice(RESUME_CLOSINGS),
    ])
    return text, own_skills, years


def make_label(required_skills, years_required, own_skills, years, rng):
    overlap_ratio = len(required_skills & own_skills) / len(required_skills)
    years_ok = years >= years_required - 1
    base_label = 1 if (overlap_ratio >= 0.6 and years_ok) else 0
    # 7% label noise: real-world "fit" judgments aren't a clean threshold
    # rule, so a small amount of flipped labels keeps the task from being
    # trivially separable.
    if rng.random() < 0.07:
        base_label = 1 - base_label
    return base_label


class Command(BaseCommand):
    help = "Generates the synthetic resume/JD fit dataset used to train both models."

    def add_arguments(self, parser):
        parser.add_argument("--n", type=int, default=1100, help="Number of rows to generate.")
        parser.add_argument("--seed", type=int, default=42, help="Random seed, for reproducibility.")

    def handle(self, *args, **options):
        rng = random.Random(options["seed"])
        n = options["n"]

        rows = []
        for _ in range(n):
            jd_role = rng.choice(ROLES)
            jd_text, required_skills, years_required = build_jd(jd_role, rng)

            # ~35% of pairs are same-role: most real applications are
            # mismatches, so this keeps the dataset realistically imbalanced.
            candidate_role = jd_role if rng.random() < 0.35 else rng.choice(
                [r for r in ROLES if r != jd_role]
            )
            resume_text, own_skills, years = build_resume(candidate_role, rng)
            label = make_label(required_skills, years_required, own_skills, years, rng)

            rows.append({
                "resume_text": resume_text,
                "jd_text": jd_text,
                "label": label,
                "jd_role": jd_role,
                "candidate_role": candidate_role,
            })

        out_path = Path(settings.DATASET_PATH)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(
                f, fieldnames=["resume_text", "jd_text", "label", "jd_role", "candidate_role"]
            )
            writer.writeheader()
            writer.writerows(rows)

        positive = sum(row["label"] for row in rows)
        self.stdout.write(self.style.SUCCESS(
            f"Wrote {len(rows)} rows to {out_path} "
            f"({positive} good-fit / {len(rows) - positive} not-a-fit)"
        ))
